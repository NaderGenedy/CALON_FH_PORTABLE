load_frozen_coefficients <- function(filepath, model_name) {
  if (file.exists(filepath)) {
    coef_df <- read.csv(filepath, stringsAsFactors = FALSE)
    coef_list <- setNames(as.list(coef_df$coefficient), coef_df$variable)
    # Rename "(Intercept)" to "intercept" for consistency
    names(coef_list)[names(coef_list) == "(Intercept)"] <- "intercept"
    cat(sprintf("  >> Loaded %s from CSV (%d coefficients)\n", model_name, length(coef_list)))
    return(coef_list)
  } else {
    cat(sprintf("  !! WARNING: %s not found. Using FALLBACK coefficients.\n", filepath))
    cat(sprintf("     Run 99_extract_frozen_coefficients.R first to generate exact values.\n"))
    return(NULL)
  }
}

