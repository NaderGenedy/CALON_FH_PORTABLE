# ── Sensitivity 1: Age-at-treatment scenarios ───────────────────────────────
cat("  1. Age-at-treatment sensitivity (lipid-year scenarios):\n")
for (scenario in c("A", "B", "C")) {
  ly_col <- paste0("lipid_years_", scenario)
  df$lp_sens <- with(df,
    CALON_CORE_COEF$intercept +
    CALON_CORE_COEF$age         * age +
    CALON_CORE_COEF$re_ldl      * re_ldl +
    CALON_CORE_COEF$lipid_years * df[[ly_col]] +
    CALON_CORE_COEF$inv_hdl     * inv_hdl
  )
  df$prob_sens <- 1 / (1 + exp(-df$lp_sens))

  sens_df <- df %>% filter(tier2_eligible == 1 & !is.na(ascvd_combined))
  if (sum(sens_df$ascvd_combined) >= 5) {
    roc_sens <- roc(sens_df$ascvd_combined, sens_df$prob_sens, quiet = TRUE)
    cat(sprintf("    Scenario %s: AUC %.3f\n", scenario, auc(roc_sens)))
  }
}

# ── Sensitivity 2: Exclude prevalent events ─────────────────────────────────
cat("\n  2. Incident-only analysis (exclude prevalent ASCVD):\n")
incident_only <- df %>%
  filter(ascvd_prevalent == 0 & tier2_eligible == 1 & !is.na(ascvd_incident))
if (sum(incident_only$ascvd_incident) >= 5) {
  roc_inc <- roc(incident_only$ascvd_incident, incident_only$prob_calon_core, quiet = TRUE)
  cat(sprintf("    CALON-CORE AUC (incident only): %.3f (n=%d, events=%d)\n",
              auc(roc_inc), nrow(incident_only), sum(incident_only$ascvd_incident)))
}

# ── Sensitivity 3: Statin-adjusted LDL assumption ──────────────────────────
cat("\n  3. Alternative residual factor assumptions:\n")
for (rf_adjust in c(0.9, 1.0, 1.1)) {
  df$re_ldl_alt <- df$ldl / (df$residual_factor * rf_adjust)
  df$lp_alt <- with(df,
    CALON_CORE_COEF$intercept +
    CALON_CORE_COEF$age         * age +
    CALON_CORE_COEF$re_ldl      * re_ldl_alt +
    CALON_CORE_COEF$lipid_years * (re_ldl_alt * pmax(0, age_treatment_A - 18) / 10) +
    CALON_CORE_COEF$inv_hdl     * inv_hdl
  )
  df$prob_alt <- 1 / (1 + exp(-df$lp_alt))
  alt_df <- df %>% filter(tier2_eligible == 1 & !is.na(ascvd_combined))
  if (sum(alt_df$ascvd_combined) >= 5) {
    roc_alt <- roc(alt_df$ascvd_combined, alt_df$prob_alt, quiet = TRUE)
    cat(sprintf("    RF multiplier %.1f: AUC %.3f\n", rf_adjust, auc(roc_alt)))
  }
}

