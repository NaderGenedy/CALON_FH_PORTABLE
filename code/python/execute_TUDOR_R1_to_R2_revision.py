NUM_PATTERNS = [
    r'\b\d+\.\d+(?:e[-+]?\d+)?\b',          # decimals incl. exponentials
    r'\b\d+(?:,\d{3})+\b',                  # 1,234 / 12,345 / 1,234,567
    r'\b\d+%\b',                            # percentages
    r'\b\d+\s*(?:nmol|mmol|mg|g|kg|mL|μmol)/L\b',  # concentrations
    r'\bp\s*=\s*[\d.]+(?:\s*[×x]\s*10[\-^][0-9]+)?\b',  # p-values
    r'\b(?:HR|OR|RR|AUC|NRI|IDI|CI)\s*[=:]\s*[\d.]+\b',  # stats
]

def extract_numbers(docx_path):
    doc = Document(str(docx_path))
    text = '\n'.join(p.text for p in doc.paragraphs)
    for tbl in doc.tables:
        for row in tbl.rows:
            for cell in row.cells:
                text += '\n' + cell.text
    found = []
    for pat in NUM_PATTERNS:
        found.extend(re.findall(pat, text))
    return sorted(found)

