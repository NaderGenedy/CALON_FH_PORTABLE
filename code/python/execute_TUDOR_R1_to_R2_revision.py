# Rule: italicise STANDALONE gene symbols. Leave protein forms (LDL-R, ApoB,
# ApoE) as-is. PCSK9 ambiguous (gene == protein typographically) — italicise.
# ============================================================================
GENE_PATTERN = re.compile(r'\b(LDLR|APOB|PCSK9|APOE)\b')
PROTEIN_NEGATIVE_LOOKBEHIND = ['LDL-R', 'ApoB', 'ApoE', 'apoB', 'apoE']

italics_count = 0
italics_locations = []
for para_idx, para in enumerate(doc.paragraphs):
    for run in list(para.runs):
        if not run.text:
            continue
        # Skip if already italic
        if run.italic:
            continue
        # Find gene-symbol matches in run text
        matches = list(GENE_PATTERN.finditer(run.text))
        if not matches:
            continue
        # Split the run at matches and italicise the gene-symbol portions
        old_text = run.text
        new_segments = []
        pos = 0
        for m in matches:
            # Check no protein-form context (e.g., "LDL-R" not "LDLR")
            before_char = old_text[max(0, m.start()-1):m.start()]
            if before_char == '-':
                continue  # skip "LDL-R"-like patterns
            new_segments.append((old_text[pos:m.start()], False))
            new_segments.append((m.group(), True))
            pos = m.end()
        new_segments.append((old_text[pos:], False))
        # Filter empty
        new_segments = [s for s in new_segments if s[0]]
        if not any(s[1] for s in new_segments):
            continue  # no italics actually applied (all in protein context)
        # Rewrite the run: keep original run as the first non-italic segment,
        # then add new runs for the rest
        run.text = new_segments[0][0]
        run.italic = new_segments[0][1]
        for seg_text, is_italic in new_segments[1:]:
            new_run = para.add_run(seg_text)
            new_run.italic = is_italic
            # Preserve original font properties
            new_run.font.name = run.font.name
            if run.font.size: new_run.font.size = run.font.size
        italics_count += sum(1 for _, ital in new_segments if ital)
        italics_locations.append((para_idx, para.text[:80]))

